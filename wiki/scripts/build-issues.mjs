// Builds assets/issues.js — the "Issues" layer: one hub per looks problem listing every approach.
// Source: research/issues/TAXONOMY.json + research/issues/*.json (issue-mapping output).
// Also merges any approach that isn't in the wiki yet into research/new-entries.json so it gets researched.
// Run: node wiki/scripts/build-issues.mjs
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { root, loadData } from './entries.mjs';

const dir = join(root, 'research', 'issues');
const TAX = JSON.parse(readFileSync(join(dir, 'TAXONOMY.json'), 'utf8'));
const KINDS = ['compound', 'gear', 'meta'];
const TIERS = ['evidence', 'mainstream', 'forum', 'fringe', 'dangerous'];
const META_CATS = ['hardmaxx', 'bonehacks', 'height', 'protocols', 'lifestyle', 'fringe', 'frameworks', 'stylemetas'];
const { D } = loadData();
const compoundCats = Object.keys(D.categoryMeta), gearCats = Object.keys(D.gearCategoryMeta);
const validCat = (k, c) => (k === 'compound' ? compoundCats : k === 'gear' ? gearCats : META_CATS).includes(c);

const byIssue = new Map();
for (const f of readdirSync(dir).filter((f) => /^[A-Z]\.json$/.test(f))) {
  let arr = [];
  try { arr = JSON.parse(readFileSync(join(dir, f), 'utf8')); } catch (e) { console.warn('skip', f, e.message); continue; }
  for (const blk of arr) if (blk?.issue) byIssue.set(blk.issue, blk);
}

// Known names (app Index + queued/published wiki entries)
const newPath = join(root, 'research', 'new-entries.json');
const queued = existsSync(newPath) ? JSON.parse(readFileSync(newPath, 'utf8')) : [];
const known = new Map([...D.compounds.map((x) => [x.name.toLowerCase(), { name: x.name, kind: 'compound' }]), ...D.gear.map((x) => [x.name.toLowerCase(), { name: x.name, kind: 'gear' }]),
  ...queued.map((x) => [x.name.toLowerCase(), { name: x.name, kind: x.kind }])]);
// Also match on aka/"Name (aka)" forms
const stripParen = (s) => s.toLowerCase().replace(/\s*\(.*?\)\s*/g, ' ').trim();
const known2 = new Map([...known.entries()].map(([k, v]) => [stripParen(k), v]));

const issues = [];
let added = 0;
for (const t of TAX) {
  const blk = byIssue.get(t.id) || { approaches: [] };
  const seen = new Set();
  const approaches = [];
  for (const a of blk.approaches || []) {
    if (!a?.name || !KINDS.includes(a.kind)) continue;
    // Entries researched and rejected (skip objects) never get articles — leave them off topic pages.
    try { const dd = JSON.parse(readFileSync(join(root, 'research', 'deep', String(a.name).toLowerCase().replace(/\s*\(.*?\)\s*/g, ' ').trim().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '') + '.json'), 'utf8')); if (dd.skip) continue; } catch {}
    try { const dd = JSON.parse(readFileSync(join(root, 'research', 'deep', String(a.name).toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '') + '.json'), 'utf8')); if (dd.skip) continue; } catch {}
    const hit = known.get(a.name.toLowerCase()) || known2.get(stripParen(a.name));
    const name = hit ? hit.name : a.name.trim();
    const kind = hit ? hit.kind : a.kind;
    if (seen.has(name.toLowerCase())) continue;
    seen.add(name.toLowerCase());
    approaches.push({ name, kind, tier: TIERS.includes(a.tier) ? a.tier : 'mainstream', why: String(a.why || '').slice(0, 200) });
    if (!hit && validCat(a.kind, a.category)) {
      queued.push({ name, kind: a.kind, category: a.category, aka: a.aka || null, terms: (a.terms || []).map((x) => String(x).toLowerCase()).slice(0, 3), why: a.why, seenAt: a.seenAt || null, issues: [t.id] });
      known.set(name.toLowerCase(), { name, kind: a.kind }); known2.set(stripParen(name), { name, kind: a.kind });
      added++;
    } else if (!hit) {
      approaches.pop(); // invalid category and unknown → drop
    }
  }
  issues.push({ id: t.id, name: t.name, group: t.group, goal: t.goal, keywords: t.keywords || [], approaches: approaches.map(({ name, kind, why }) => ({ name, kind, why })) });
}
writeFileSync(newPath, JSON.stringify(queued, null, 1));
writeFileSync(join(root, 'assets', 'issues.js'),
  '// GENERATED by scripts/build-issues.mjs — the Issues layer (problem → every approach).\n' +
  'window.LM_ISSUES = ' + JSON.stringify(issues) + ';\n');
const total = issues.reduce((a, i) => a + i.approaches.length, 0);
console.log(`${issues.length} issues, ${total} approach links, ${issues.filter((i) => i.approaches.length).length} mapped; +${added} new entries queued (queue now ${queued.length})`);
