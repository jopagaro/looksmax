// Pulls The Index data straight out of the looksmax app (lib/compounds.ts,
// lib/gear.ts, lib/affiliates.ts) and writes it to assets/data.js so the wiki
// always mirrors the app. Run:  node wiki/scripts/sync-data.mjs
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import vm from 'node:vm';

const here = dirname(fileURLToPath(import.meta.url));
// Works both side-by-side (lookmax/wiki + lookmax/looksmax) and inside the app repo (looksmax/wiki).
const appRoot = [join(here, '..', '..', 'looksmax'), join(here, '..', '..')]
  .find((d) => existsSync(join(d, 'lib', 'compounds.ts')));
if (!appRoot) throw new Error('Could not find the looksmax app (lib/compounds.ts) next to or above the wiki.');
const ts = createRequire(join(appRoot, 'package.json'))('typescript');

function load(file) {
  const src = readFileSync(join(appRoot, 'lib', file), 'utf8');
  const js = ts.transpileModule(src, {
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 },
  }).outputText;
  const module = { exports: {} };
  // Type-only imports are elided by tsc; any real import resolves to {}.
  vm.runInNewContext(js, { module, exports: module.exports, require: () => ({}) });
  return module.exports;
}

const c = load('compounds.ts');
const g = load('gear.ts');
const aff = readFileSync(join(appRoot, 'lib', 'affiliates.ts'), 'utf8');
const pick = (re) => {
  const m = aff.match(re);
  if (!m) throw new Error('affiliates.ts shape changed: ' + re);
  return m[1];
};
// Object literals in affiliates.ts are plain JS — evaluate them in isolation.
const evalLit = (s) => vm.runInNewContext('(' + s + ')');
const affiliates = {
  amazonTag: evalLit(pick(/AMAZON_TAG\s*=\s*('[^']*')/)),
  rxPartners: evalLit(pick(/RX_PARTNERS[^=]*=\s*(\{[\s\S]*?\n\});/)),
  queryOverrides: evalLit(pick(/QUERY_OVERRIDES[^=]*=\s*(\{[\s\S]*?\n\});/)),
  noBuy: evalLit(pick(/NO_BUY\s*=\s*new Set\((\[[^\]]*\])\)/)),
};

const data = {
  syncedAt: new Date().toISOString().slice(0, 10),
  categoryMeta: c.CATEGORY_META,
  evidenceMeta: c.EVIDENCE_META,
  statusMeta: c.STATUS_META,
  compounds: c.COMPOUNDS,
  gearCategoryMeta: g.GEAR_CATEGORY_META,
  outcomeMeta: g.OUTCOME_META,
  gear: g.GEAR,
  affiliates,
};

const out = join(here, '..', 'assets', 'data.js');
writeFileSync(
  out,
  '// GENERATED by scripts/sync-data.mjs from looksmax/lib — do not edit by hand.\n' +
    'window.LM_DATA = ' + JSON.stringify(data, null, 1) + ';\n'
);
console.log(`wrote ${out}: ${data.compounds.length} compounds, ${data.gear.length} gear`);
