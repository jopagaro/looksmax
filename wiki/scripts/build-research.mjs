// Merges research/NN-*.json (written by the research pass) into assets/research.js.
// Drops malformed links, reports coverage. Run: node wiki/scripts/build-research.mjs
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'research');
const okUrl = (u) => typeof u === 'string' && /^https:\/\/[^\s"<>]+$/.test(u);
const str = (s) => (typeof s === 'string' ? s.trim() : '');

const out = {};
let files = 0, bad = 0;
for (const f of readdirSync(dir).filter((f) => /^\d\d-.*\.json$/.test(f)).sort()) {
  let obj;
  try { obj = JSON.parse(readFileSync(join(dir, f), 'utf8')); } catch (e) { console.warn('SKIP invalid JSON', f, e.message); continue; }
  files++;
  for (const [name, r] of Object.entries(obj)) {
    const links = (arr, keys) => (Array.isArray(arr) ? arr : []).filter((x) => {
      const ok = x && okUrl(x.url) && str(x.title);
      if (!ok) bad++;
      return ok;
    }).map((x) => Object.fromEntries(keys.map((k) => [k, k === 'year' ? (Number(x[k]) || null) : str(x[k])])));
    out[name] = {
      grokipedia: okUrl(r.grokipedia) ? r.grokipedia : null,
      overview: str(r.overview),
      mechanism: str(r.mechanism),
      risks: str(r.risks),
      scholarly: links(r.scholarly, ['title', 'url', 'source', 'year']),
      forums: links(r.forums, ['title', 'url', 'site']),
      image: okUrl(r.image) && /^https:\/\/upload\.wikimedia\.org\//.test(r.image) ? r.image : null,
      imageCredit: okUrl(r.imageCredit) ? r.imageCredit : null,
    };
  }
}
writeFileSync(join(root, 'assets', 'research.js'),
  '// GENERATED by scripts/build-research.mjs from research/*.json — do not edit by hand.\n' +
  'window.LM_RESEARCH = ' + JSON.stringify(out) + ';\n');
const v = Object.values(out);
console.log(`${files} files, ${v.length} entries | grokipedia ${v.filter((x) => x.grokipedia).length} | scholarly ${v.reduce((a, x) => a + x.scholarly.length, 0)} | forums ${v.reduce((a, x) => a + x.forums.length, 0)} | images ${v.filter((x) => x.image).length} | dropped ${bad} bad links`);
