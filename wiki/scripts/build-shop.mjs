// Builds assets/shop.js — the "Shop this" buttons on meta pages — from the meta→product matches in
// affiliate/map/out2-*.json ({slug: {products: [exact product names], extra: [Amazon search phrases]}}).
// Only Amazon-sellable wiki entries (gear + OTC compounds) are kept; Rx and research compounds never appear.
// Run: node scripts/build-shop.mjs   (build-entries runs it too)
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { root, slug, allEntries } from './entries.mjs';

const dir = join(root, 'affiliate', 'map');
if (!existsSync(dir)) { console.log('shop: no affiliate/map folder, keeping existing assets/shop.js'); process.exit(0); }
const map = {};
for (const f of readdirSync(dir).filter((f) => /^out2-\d+\.json$/.test(f))) Object.assign(map, JSON.parse(readFileSync(join(dir, f), 'utf8')));

const byName = new Map();
for (const { kind, item } of allEntries()) {
  const s = slug(item.name);
  if (!existsSync(join(root, 'data', 'entries', s + '.json'))) continue;
  if (kind === 'meta' || (kind === 'compound' && ['rx', 'research'].includes(item.status))) continue;
  byName.set(item.name.toLowerCase(), [kind, s]);
}
const shop = {};
let products = 0, extras = 0, unknown = 0;
for (const [metaSlug, v] of Object.entries(map)) {
  const p = [];
  for (const n of v.products || []) { const hit = byName.get(String(n).toLowerCase()); if (hit && !p.some((x) => x[1] === hit[1])) p.push(hit); else if (!hit) unknown++; }
  const q = [...new Set((v.extra || []).map((x) => String(x).trim().toLowerCase()).filter((x) => x.length >= 3 && x.length <= 60))].slice(0, 3);
  if (p.length || q.length) { shop[metaSlug] = { p: p.slice(0, 6), q }; products += p.length; extras += q.length; }
}
writeFileSync(join(root, 'assets', 'shop.js'), '// GENERATED by scripts/build-shop.mjs — "Shop this" products for meta pages.\n' +
  'window.LM_SHOP = ' + JSON.stringify(shop) + ';\n');
console.log(`shop: ${Object.keys(shop).length} metas with buttons (${products} product links, ${extras} extra searches; ${unknown} unmatched names skipped)`);
