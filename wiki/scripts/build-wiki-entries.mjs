// Builds assets/wiki-entries.js — entries that exist only on the wiki (not in the app's Index):
// newly discovered compounds, gear, and the Metas section (forum theories & protocols).
// Source: research/new-entries.json (the discovery list) + research/deep/<slug>.json "card"
// (the rating card written from the sources). Entries without a card are not published yet.
// Run: node wiki/scripts/build-wiki-entries.mjs
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { root, slug, loadData } from './entries.mjs';

export const META_CATEGORIES = {
  hardmaxx: { name: 'Hardmaxx procedures', blurb: 'Surgery, injectables and implants' },
  bonehacks: { name: 'Bone & structure practices', blurb: 'Non-surgical practices aimed at changing facial or skeletal structure' },
  height: { name: 'Height', blurb: 'Methods people use to increase or appear to increase height' },
  protocols: { name: 'Drug & hormone protocols', blurb: 'Stacks, cycles and regimens discussed in forums' },
  lifestyle: { name: 'Diet & lifestyle protocols', blurb: 'Diets, abstinence, cold, sun and other lifestyle practices' },
  fringe: { name: 'Alternative & fringe practices', blurb: 'Unconventional practices with little or no published research' },
  frameworks: { name: 'Forum frameworks', blurb: 'Rating systems, ratios, terminology and theories used in the community' },
  stylemetas: { name: 'Style & grooming metas', blurb: 'Presentation trends: hair, clothing, grooming and photos' },
};
const EV = ['strong', 'moderate', 'limited', 'unproven'];
const RISK = ['low', 'moderate', 'high', 'extreme'];
const STATUS = ['otc', 'rx', 'research'];
const OUTCOME = ['durable', 'temporary', 'unsupported'];

const { D } = loadData();
const appNames = new Set([...D.compounds, ...D.gear].map((x) => x.name.toLowerCase()));
let list = [];
try { list = JSON.parse(readFileSync(join(root, 'research', 'new-entries.json'), 'utf8')); } catch {}

const entries = [];
const skipped = [];
for (const n of list) {
  if (!n?.name || appNames.has(n.name.toLowerCase())) continue;
  const deepFile = join(root, 'research', 'deep', slug(n.name) + '.json');
  let card = null;
  try { card = JSON.parse(readFileSync(deepFile, 'utf8')).card; } catch {}
  if (!card || !card.summary || !EV.includes(card.evidence)) { skipped.push(n.name); continue; }
  const e = { name: n.name, kind: n.kind, category: n.category, aka: card.aka || n.aka || undefined, evidence: card.evidence, summary: String(card.summary).trim(), note: card.note ? String(card.note).trim() : undefined, wiki: true };
  if (n.kind === 'compound') e.status = STATUS.includes(card.status) ? card.status : 'research';
  if (n.kind === 'gear') { e.outcome = OUTCOME.includes(card.outcome) ? card.outcome : 'temporary'; if (card.price) e.price = String(card.price); }
  if (n.kind === 'meta') e.risk = RISK.includes(card.risk) ? card.risk : 'moderate';
  if (n.kind === 'compound' && card.structure) e.structure = String(card.structure);
  if (n.mentions) e.mentions = n.mentions;
  entries.push(e);
}
writeFileSync(join(root, 'assets', 'wiki-entries.js'),
  '// GENERATED by scripts/build-wiki-entries.mjs — wiki-only entries (discovered compounds, gear, metas).\n' +
  'window.LM_WIKI = ' + JSON.stringify({ metaCategories: META_CATEGORIES, riskLevels: RISK, entries }, null, 1) + ';\n');
const by = (k) => entries.filter((e) => e.kind === k).length;
console.log(`wiki-only entries: ${entries.length} published (compounds ${by('compound')}, gear ${by('gear')}, metas ${by('meta')}); ${skipped.length} awaiting research`);
