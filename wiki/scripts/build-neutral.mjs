// Merges research/neutral/*.json (neutral-point-of-view rewrites of the app's one-liners, notes and
// first-pass quick takes) into assets/neutral.js, which the site applies over the app's wording.
// Run: node wiki/scripts/build-neutral.mjs
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { root } from './entries.mjs';
const dir = join(root, 'research', 'neutral');
const out = {};
if (existsSync(dir)) for (const f of readdirSync(dir).filter((f) => /\.json$/.test(f))) {
  try { for (const [k, v] of Object.entries(JSON.parse(readFileSync(join(dir, f), 'utf8')))) out[k] = { summary: v.summary || null, note: v.note || null }; } catch (e) { console.warn('skip', f, e.message); }
}
writeFileSync(join(root, 'assets', 'neutral.js'), '// GENERATED by scripts/build-neutral.mjs — neutral wording for Index one-liners and notes.\nwindow.LM_NEUTRAL = ' + JSON.stringify(out) + ';\n');
console.log('neutral overrides:', Object.keys(out).length);
