/** PubChem 2D structure image by compound name. */
export function structureUrl(query: string): string {
  return `https://pubchem.ncbi.nlm.nih.gov/rest/pug/compound/name/${encodeURIComponent(
    query
  )}/PNG?record_type=2d&image_size=large`;
}

